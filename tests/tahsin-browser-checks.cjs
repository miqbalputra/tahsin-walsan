/** Run against the isolated staging router only. Set NODE_PATH to Playwright's package directory. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TAHSIN_TEST_URL || 'http://127.0.0.1:18081';
if (new URL(base).hostname !== '127.0.0.1') throw new Error('Only isolated localhost staging is allowed');
const output = path.resolve('.sessions/tahsin-ui');
fs.mkdirSync(output, {recursive: true});
let checks = 0;
function check(value, message) { assert(value, message); checks++; }
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.TAHSIN_TEST_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const errors = [];
  async function login(username, viewport = {width: 1600, height: 1000}) {
    const context = await browser.newContext({viewport});
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/login.php');
    await page.locator('[name=username]').fill(username);
    await page.locator('[name=password]').fill('TahsinTest-2026');
    const csrf = await page.locator('[name=csrf_token]').inputValue();
    await Promise.all([page.waitForURL(/dashboard\.php/), page.locator('button[type=submit]').click()]);
    return {context, page, csrf};
  }
  try {
    const {context, page} = await login('admin_test');
    check(await page.locator('.tahsin-widget').count() === 1, 'Dashboard has pending-input summary');
    await page.goto(base + '/rekap-lengkap.php');
    await page.waitForFunction(() => window.Chart && Chart.getChart(document.getElementById('tahsin-trend')));
    check(await page.locator('.tahsin-wali tbody tr').count() === 50, 'First page lists fifty parents');
    check(await page.getByText('Rekap Seluruh Wali · 60 orang', {exact: true}).count() === 1, 'Report includes every parent');
    check(await page.locator('.tahsin-card').nth(3).locator('strong').innerText() === '50%', 'Screen attendance is fifty percent');
    check(await page.locator('.tahsin-card').nth(4).locator('strong').innerText() === '50%', 'Screen completeness is fifty percent');
    await page.screenshot({path: path.join(output, 'rekap-desktop.png'), fullPage: true});
    await page.goto(base + '/rekap-lengkap.php?page=2');
    check(await page.locator('.tahsin-wali tbody tr').count() === 10, 'Remaining parents are reachable');
    await page.goto(base + '/rekap-lengkap.php?search=Santri+Uji+Kedua');
    check(await page.locator('.tahsin-wali tbody tr').count() === 1, 'Child search deduplicates parents');
    await page.goto(base + '/rekap-lengkap.php?mode=rapat');
    check(!(await page.locator('[data-sidebar]').isVisible()), 'Meeting mode hides entire sidebar');
    check(!(await page.locator('header').isVisible()), 'Meeting mode hides app navbar');
    check(!(await page.locator('body').innerText()).includes('0813 9029'), 'Meeting does not show contact phone');
    await page.screenshot({path: path.join(output, 'rekap-rapat.png'), fullPage: true});
    const excel = await context.request.get(base + '/rekap-lengkap.php?export=excel');
    check(excel.status() === 200, 'Excel export works');
    const excelText = await excel.text();
    check(excelText.includes('Wali Uji 60') && excelText.includes('Wali Uji 01'), 'Export contains all pages');
    check(!excelText.includes('081234567890'), 'Export excludes telephone numbers');
    fs.writeFileSync(path.join(output, 'rekap-semua.xls'), excelText);
    await page.goto(base + '/rekap-lengkap.php?print=1');
    check(await page.locator('.tahsin-wali tbody tr').count() === 60, 'Print includes every parent');
    await page.emulateMedia({media: 'print'});
    check(!(await page.locator('[data-sidebar]').isVisible()), 'Print hides sidebar');
    check(!(await page.locator('body').innerText()).includes('0813 9029'), 'Print hides about-modal contact phone');
    await page.pdf({path: path.join(output, 'rekap-semua.pdf'), printBackground: true, preferCSSPageSize: true});
    await page.emulateMedia({media: 'screen'});
    await page.goto(base + '/pantau-input.php');
    check((await page.locator('body').innerText()).includes('Wali Uji 03'), 'Pending page names the missing participant');
    check(await page.getByRole('link', {name: 'Buka Pengingat WhatsApp', exact: true}).count() === 1, 'Manual WhatsApp action is available');
    const wa = new URL(await page.getByRole('link', {name: 'Buka Pengingat WhatsApp', exact: true}).getAttribute('href'));
    check(wa.searchParams.get('text').includes(base + '/ustadz/form-presensi.php'), 'WhatsApp contains a valid absolute form link');
    await page.screenshot({path: path.join(output, 'pantau-desktop.png'), fullPage: true});
    const capaianApi = await context.request.get(base + '/api/hermes.php?action=capaian', {headers: {'X-API-Key': 'tahsin-test-api'}});
    const initialPosition = (await capaianApi.json()).data.find(row => row.wali_id === 3);
    check(initialPosition.is_initial === true && initialPosition.last_date === null && initialPosition.hasil_talaqqi === null, 'Initial material is exposed without fabricated attendance or pass');
    const unauthorized = await context.request.post(base + '/rekap-lengkap.php', {form: {action: 'verify', csrf_token: 'wrong'}});
    check(unauthorized.status() === 403, 'Invalid CSRF is rejected');
    const apiFail = await context.request.get(base + '/api/daily-reminder.php');
    check(apiFail.status() === 401, 'Reminder data requires API key');
    const api = await context.request.get(base + '/api/daily-reminder.php', {headers: {'X-API-Key': 'tahsin-test-api'}});
    const pending = await api.json();
    check(pending.status === 'success' && pending.data[0].missing_presensi === 2, 'Reminder API shares report counts');
    const stats = await context.request.get(base + '/api/hermes.php?action=stats', {headers: {'X-API-Key': 'tahsin-test-api'}});
    check((await stats.json()).data.ringkasan.hadir_percent === 50, 'Hermes shares official ratios');
    for (const route of ['progress-wali.php', 'rekap-halaqoh.php', 'laporan-bulanan.php']) {
      await page.goto(base + '/' + route);
      check(await page.locator('.tahsin-card').nth(3).locator('strong').innerText() === '50%', route + ' shares attendance totals');
    }
    const {context: teacherContext, page: teacher} = await login('guru_test');
    await teacher.goto(base + '/rekap-lengkap.php');
    check(await teacher.locator('.tahsin-wali tbody tr').count() === 4, 'Teacher sees only assigned parents');
    check(await teacher.locator('form.tahsin-verify').count() === 0, 'Teacher cannot verify conflicts');
    await teacher.goto(base + '/pantau-input.php');
    check(await teacher.getByRole('link', {name: 'Buka Pengingat WhatsApp', exact: true}).count() === 0, 'Teacher does not get admin message actions');
    await teacher.goto(base + '/ustadz/form-presensi.php?id=1&tanggal=2026-10-11');
    check((await teacher.locator('body').innerText()).includes('Sesi Ahad 11/10/2026'), 'Session form explains weekly identity');
    const csrf = await teacher.locator('form [name=csrf_token]').first().inputValue();
    const badSave = await teacherContext.request.post(base + '/ustadz/api-save-single.php', {form: {csrf_token: csrf, halaqoh_id: '1', wali_santri_id: '3', tanggal: '2026-10-11'}});
    check(badSave.status() === 422, 'Omitted status cannot become alpha');
    const incompleteH = await teacherContext.request.post(base + '/ustadz/api-save-single.php', {form: {csrf_token: csrf, halaqoh_id: '1', wali_santri_id: '3', tanggal: '2026-10-11', status: 'H', jenis_materi: 'Iqro'}});
    check(incompleteH.status() === 422, 'H cannot be saved without complete achievement');
    const otherTeacher = await login('guru_lain');
    await otherTeacher.page.goto(base + '/rekap-lengkap.php');
    check(!(await otherTeacher.page.locator('body').innerText()).includes('Wali Uji 01'), 'Other teacher cannot read this parent');
    const forbiddenSave = await otherTeacher.context.request.post(base + '/ustadz/api-save-single.php', {form: {csrf_token: otherTeacher.csrf, halaqoh_id: '1', wali_santri_id: '1', tanggal: '2026-10-11', status: 'A'}});
    check(forbiddenSave.status() === 422, 'Valid teacher session cannot write another teacher attendance');
    const {context: kepsekContext, page: kepsek, csrf: kepsekCsrf} = await login('kepsek_test');
    await kepsek.goto(base + '/rekap-lengkap.php');
    check(await kepsek.locator('.tahsin-wali tbody tr').count() === 50, 'Headmaster reads complete report');
    const kepsekToken = await kepsekContext.cookies();
    const denied = await kepsekContext.request.post(base + '/rekap-lengkap.php', {form: {action: 'verify', csrf_token: kepsekCsrf}});
    check(denied.status() === 403 && kepsekToken.length > 0, 'Headmaster write request is denied even when logged in');
    await kepsek.goto(base + '/pantau-input.php');
    check(await kepsek.getByRole('link', {name: 'Buka Pengingat WhatsApp', exact: true}).count() === 0, 'Headmaster reminder view is read-only');
    const mobile = await login('admin_test', {width: 390, height: 844});
    await mobile.page.goto(base + '/rekap-lengkap.php');
    await mobile.page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().right <= 1);
    await mobile.page.evaluate(() => document.fonts.ready);
    check(await mobile.page.locator('[data-sidebar]').evaluate(node => node.getBoundingClientRect().right <= 1), 'Mobile navigation starts closed');
    check(await mobile.page.evaluate(() => document.documentElement.scrollWidth <= 390), 'Mobile page has no body overflow');
    await mobile.page.screenshot({path: path.join(output, 'rekap-mobile.png'), fullPage: true});
    await mobile.page.goto(base + '/pantau-input.php');
    await mobile.page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().right <= 1);
    await mobile.page.evaluate(() => document.fonts.ready);
    check(await mobile.page.evaluate(() => document.documentElement.scrollWidth <= 390), 'Mobile reminder has no body overflow');
    await mobile.page.screenshot({path: path.join(output, 'pantau-mobile.png'), fullPage: true});
    check(errors.length === 0, 'No browser JavaScript errors: ' + errors.join('; '));
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({checks, errors, result: 'PASS'}, null, 2));
    console.log(`PASS ${checks} browser checks; previews: ${output}`);
  } finally { await browser.close(); }
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
